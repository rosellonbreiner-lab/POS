async function runSeed() {
  console.log(`Iniciando inserción de ${productsData.length} repuestos comunes en Colombia...`);

  // Crear o asegurar categorías
  const categories = Array.from(new Set(productsData.map((p) => p.category)));
  const categoryMap = new Map<string, string>();
  for (const catName of categories) {
    const cat = await prisma.category.upsert({
      where: { name: catName },
      update: {},
      create: { name: catName, description: `Repuestos y partes de ${catName}` },
    });
    categoryMap.set(catName, cat.id);
  }

  // Crear o asegurar marcas
  const brands = Array.from(new Set(productsData.map((p) => p.brand)));
  const brandMap = new Map<string, string>();
  for (const brandName of brands) {
    const b = await prisma.brand.upsert({
      where: { name: brandName },
      update: {},
      create: { name: brandName },
    });
    brandMap.set(brandName, b.id);
  }

  // Insertar o actualizar los 200 productos
  let inserted = 0;
  for (const item of productsData) {
    const catId = categoryMap.get(item.category);
    const bId = brandMap.get(item.brand);

    const product = await prisma.product.upsert({
      where: { sku: item.sku },
      update: {
        name: item.name,
        motorcycleFit: item.motorcycleFit,
        costPrice: item.costPrice,
        salePrice: item.salePrice,
        currentStock: item.currentStock,
        minStock: item.minStock,
        categoryId: catId,
        brandId: bId,
      },
      create: {
        sku: item.sku,
        name: item.name,
        motorcycleFit: item.motorcycleFit,
        costPrice: item.costPrice,
        salePrice: item.salePrice,
        currentStock: item.currentStock,
        minStock: item.minStock,
        categoryId: catId,
        brandId: bId,
      },
    });

    // Ubicación física
    const location = await prisma.location.upsert({
      where: {
        warehouse_shelf_level_position: {
          warehouse: "Bodega Principal",
          shelf: item.shelf,
          level: item.level,
          position: "A-1",
        },
      },
      update: {},
      create: {
        warehouse: "Bodega Principal",
        shelf: item.shelf,
        level: item.level,
        position: "A-1",
      },
    });

    await prisma.productLocation.upsert({
      where: {
        productId_locationId: {
          productId: product.id,
          locationId: location.id,
        },
      },
      update: {},
      create: {
        productId: product.id,
        locationId: location.id,
      },
    });

    inserted++;
  }

  console.log(`[EXITO] Se cargaron ${inserted} repuestos reales para Boxer, NKD, Eco Deluxe y motos comunes en Colombia.`);
}

runSeed()
  .catch((e) => {
    console.error("Error cargando repuestos:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });

